/**
 * Spell upcast-parsing coverage report.
 *
 * Runs the SAME parser the Cast dialog uses (spellUpcast.classifyUpcast) over the entire live
 * spell catalog and reports, per spell, whether its upcast is:
 *   - none        — no "At Higher Levels" text (nothing to compute; fine)
 *   - computed    — the dialog can show exact damage/healing dice at the chosen slot
 *   - prose-only  — has upcast text the parser can't turn into a number, so the dialog falls
 *                   back to the verbatim rules text (more targets, duration, DC thresholds,
 *                   ambiguous dice, …). THIS is the review worklist.
 *
 * The prose-only list is written to docs/spell-upcast-review.md so we can decide later which of
 * those deserve structured upcast data (vs. staying honest prose). Re-run any time spells are
 * added (new sourcebook seed, GM homebrew) — no re-analysis by hand.
 *
 * Requires the backend running (spells live in the DB). Auth defaults to the GM test account;
 * override with UPCAST_REPORT_EMAIL / UPCAST_REPORT_PASSWORD / API_BASE.
 *
 * Run: npm run report:upcast-coverage   (from frontend/, backend up)
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { classifyUpcast } from '../src/characters/components/spells/spellUpcast.js';

const API_BASE = process.env.API_BASE || 'http://localhost:8000';
const EMAIL = process.env.UPCAST_REPORT_EMAIL || 'gm@dnd.com';
const PASSWORD = process.env.UPCAST_REPORT_PASSWORD || 'password123';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = resolve(__dirname, '../../docs/spell-upcast-review.md');

async function login() {
  const res = await fetch(`${API_BASE}/api/auth/login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: EMAIL, password: PASSWORD }),
  });
  if (!res.ok) throw new Error(`login failed (${res.status}) — is the backend up? is ${EMAIL} a valid account?`);
  return (await res.json()).access_token;
}

async function fetchSpells(token) {
  const res = await fetch(`${API_BASE}/api/encyclopedia/spells`, {
    headers: { Authorization: `Bearer ${token}` },
  });
  if (!res.ok) throw new Error(`fetch spells failed (${res.status})`);
  return res.json();
}

function ordinal(n) {
  return ['none', '1st', '2nd', '3rd', '4th', '5th', '6th', '7th', '8th', '9th'][n] ?? `${n}th`;
}

async function main() {
  const token = await login();
  const spells = await fetchSpells(token);

  const buckets = { none: [], computed: [], 'prose-only': [] };
  for (const spell of spells) {
    const { status, reason } = classifyUpcast(spell);
    buckets[status].push({ ...spell, reason });
  }

  const total = spells.length;
  const scaling = buckets.computed.length + buckets['prose-only'].length;
  console.log(`\nSpell upcast coverage — ${total} spells (edition-tagged rows counted individually)`);
  console.log(`  none        ${buckets.none.length}\t(no At Higher Levels text)`);
  console.log(`  computed    ${buckets.computed.length}\t(exact dice shown in the Cast dialog)`);
  console.log(`  prose-only  ${buckets['prose-only'].length}\t(upcast text shown verbatim — review list)`);
  console.log(`\nOf the ${scaling} spells that DO scale, ${buckets.computed.length} compute cleanly ` +
    `(${scaling ? Math.round((buckets.computed.length / scaling) * 100) : 0}%).`);

  // Group the review list by reason for easier triage.
  const proseByReason = {};
  for (const s of buckets['prose-only']) {
    (proseByReason[s.reason] ||= []).push(s);
  }

  const lines = [];
  lines.push('# Spell upcast — review worklist');
  lines.push('');
  lines.push('_Auto-generated by `npm run report:upcast-coverage`. Do not edit by hand — re-run to refresh._');
  lines.push('');
  lines.push(`Catalog: **${total}** spells · scaling: **${scaling}** · computed: **${buckets.computed.length}** · prose-only: **${buckets['prose-only'].length}**`);
  lines.push('');
  lines.push('These spells have "At Higher Levels" text the parser can\'t turn into a computed number, so');
  lines.push('the Cast dialog shows their rules text verbatim (always honest, just not a headline figure).');
  lines.push('Decide per group whether structured upcast data is worth authoring.');
  lines.push('');
  for (const reason of Object.keys(proseByReason).sort()) {
    const group = proseByReason[reason].sort((a, b) => a.name.localeCompare(b.name));
    lines.push(`## ${reason} — ${group.length}`);
    lines.push('');
    for (const s of group) {
      const ed = s.edition && s.edition !== '5e' ? ` _(${s.edition})_` : '';
      lines.push(`- **${s.name}** (${ordinal(s.level)})${ed} — ${(s.higher_level || '').replace(/\s+/g, ' ').trim()}`);
    }
    lines.push('');
  }

  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, lines.join('\n'), 'utf8');
  console.log(`\nReview list written to docs/spell-upcast-review.md`);
}

main().catch((err) => {
  console.error(`\n${err.message}\n`);
  process.exit(1);
});
